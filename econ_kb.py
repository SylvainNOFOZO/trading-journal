def describe(title, country=""):
    """Retourne la fiche de l'indicateur (dict) avec la liste de liens à afficher."""
    t = (title or "").lower()
    entry = next((e for e in KB if any(k in t for k in e["keys"])), GENERIC)
    pub = entry["pub"].get(country) or entry["pub"].get("*") or next(iter(entry["pub"].values()), "—")
    links = list(entry["links"])
    if country in CCY_LINKS:
        links.append(CCY_LINKS[country])
    if not links:
        links.append(GENERIC_LINK)
    return dict(name=entry["name"] or title, what=entry["what"], pub=pub, freq=entry["freq"],
                why=entry["why"], up=entry["up"], down=entry["down"], links=links,
                known=entry is not GENERIC)
